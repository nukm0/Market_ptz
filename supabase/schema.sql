-- Aggregate views remove repeated client-side counting and speed up shop/subscriber lists.
create or replace view public.marketplace_shop_subscription_counts as
select shop_id, count(*)::integer as subscriber_count
from public.marketplace_shop_subscriptions
group by shop_id;

create or replace view public.marketplace_profile_subscription_counts as
select target_telegram_id, count(*)::integer as subscriber_count
from public.marketplace_profile_subscriptions
group by target_telegram_id;

