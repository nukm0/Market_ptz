-- Count only authenticated Telegram sessions; one record per listing view and viewer.
create table if not exists public.marketplace_listing_views (
  id uuid primary key default gen_random_uuid(),
  listing_id text not null,
  seller_username text,
  viewer_telegram_id bigint not null,
  created_at timestamptz not null default now()
);
create index if not exists marketplace_listing_views_viewer_idx on public.marketplace_listing_views(viewer_telegram_id, created_at desc);
create index if not exists marketplace_listing_views_listing_idx on public.marketplace_listing_views(listing_id, created_at desc);
-- The view endpoint upserts once per viewer/listing. Deduplicate legacy rows before adding the key.
delete from public.marketplace_listing_views older
using public.marketplace_listing_views newer
where older.listing_id = newer.listing_id
  and older.viewer_telegram_id = newer.viewer_telegram_id
  and older.ctid < newer.ctid;
create unique index if not exists marketplace_listing_views_listing_viewer_uidx
  on public.marketplace_listing_views(listing_id, viewer_telegram_id);
alter table public.marketplace_listing_views enable row level security;
alter table public.marketplace_shops add column if not exists display_order integer not null default 9999;

alter table public.marketplace_users add column if not exists referred_by bigint;
alter table public.marketplace_users add column if not exists referral_attributed_at timestamptz;
create index if not exists marketplace_users_referred_by_idx on public.marketplace_users(referred_by);

create unique index if not exists marketplace_listing_views_unique_viewer_idx on public.marketplace_listing_views(listing_id, viewer_telegram_id);


