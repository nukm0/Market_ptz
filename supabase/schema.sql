-- Marketplace production persistence. Run this in the Supabase SQL editor.
create extension if not exists pgcrypto;
create table if not exists public.marketplace_users (
  telegram_id bigint primary key,
  username text,
  first_name text,
  last_name text,
  photo_url text,
  verified boolean not null default false,
  verified_by bigint,
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.marketplace_staff_roles (
  telegram_id bigint primary key,
  role text not null check (role in ('Заместитель владельца','Администратор','Модератор','Стажёр','Магазин')),
  assigned_by bigint not null,
  updated_at timestamptz not null default now()
);
create table if not exists public.marketplace_shops (
  id uuid primary key default gen_random_uuid(),
