create table if not exists public.marketplace_reviews (
  id uuid primary key default gen_random_uuid(),
  author_telegram_id bigint not null,
  target_type text not null check (target_type in ('profile','shop')),
  target_telegram_id bigint,
  target_shop_id uuid references public.marketplace_shops(id) on delete cascade,
  target_title text not null default '',
  stars integer not null check (stars between 1 and 5),
  description text not null default '',
  status text not null default 'pending' check (status in ('pending','approved','rejected','hidden','disputed')),
  dispute_text text,
  moderator_comment text,
  reviewed_by bigint,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  constraint marketplace_reviews_target_check check ((target_type='profile' and target_telegram_id is not null) or (target_type='shop' and target_shop_id is not null))
);
create index if not exists marketplace_reviews_target_profile_idx on public.marketplace_reviews(target_telegram_id, status, created_at desc);
create index if not exists marketplace_reviews_target_shop_idx on public.marketplace_reviews(target_shop_id, status, created_at desc);
create index if not exists marketplace_reviews_author_idx on public.marketplace_reviews(author_telegram_id, created_at desc);
alter table public.marketplace_reviews enable row level security;

